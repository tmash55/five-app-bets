"""Renders the card art for a roster: one full-figure picture and one head shot per player.

    python tools/blender/render_cards.py                      # the neighborhood league
    python tools/blender/render_cards.py --only dash-bennett  # just some players
    python tools/blender/render_cards.py --roster private/roster/roster.json --out private/roster/art --ts private/roster/art.ts

Pictures are transparent PNGs. A small TypeScript file that `require`s each one
is written next to them so the app can look pictures up by player id.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import sys
import time
import zlib
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bpy  # noqa: E402
from mathutils import Vector  # noqa: E402

from mk import assemble, geo, props, studio  # noqa: E402
from mk.figure import Quality  # noqa: E402
from mk.poses import BALL, POSES  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]

ROLE_POSES = {
    "Sharpshooter": ["present", "point"],
    "High Flyer": ["cheer", "present"],
    "Speedster": ["dribble", "dribble", "point"],
    "Playmaker": ["hold", "present"],
    "Lockdown": ["ready", "hip"],
    "Big": ["flex", "hip"],
    "All-Around": ["hip", "hold"],
}

# how the toy is turned for its picture, per pose (degrees, positive turns its face to the camera's right)
POSE_YAW = {"dribble": -24, "point": 16, "hip": -14, "present": 12, "cheer": 10, "flex": 8, "hold": -10, "ready": 14, "wave": 10}


def pick_pose(player: dict) -> str:
    if "pose" in player:
        return player["pose"]
    options = ROLE_POSES.get(player["role"], ["ready"])
    return options[zlib.crc32(player["id"].encode()) % len(options)]


def look_for(player: dict, team: dict) -> dict:
    look = dict(player["look"])
    look["number"] = str(player["number"])
    look["kit"] = {**team["kit"], **look.get("kit", {})}
    return look


def add_ball(rig, pose: str, q: Quality):
    if pose not in BALL:
        return
    bone, off = BALL[pose]
    bpy.context.view_layer.update()
    mw = rig.bones[bone].matrix_world
    pal = {"ball": "#E8792B", "seam": "#2A1A14"}
    ball = geo.to_object("ball", props.make_ball(q), lambda s: assemble.vinyl_material("ball", pal[s], s))
    ball.location = mw @ Vector(off)
    ball.rotation_euler = (0.5, 0.9, 0.4)
    return ball


def render_player(player: dict, team: dict, out_cards: Path, out_heads: Path, size, head_px: int, samples: int):
    q = Quality(2.0, decal_offset=0.002)
    look = look_for(player, team)
    pose = pick_pose(player)

    # --- full figure ---
    scene = studio.reset_scene()
    studio.setup_cycles(scene, samples=samples, width=size[0], height=size[1], transparent=True)
    rig = assemble.spawn_figure("p", look, q)
    rig.anchor.rotation_euler = (0, 0, math.radians(POSE_YAW.get(pose, 10)))
    rig.pose(POSES[pose])
    add_ball(rig, pose, q)
    studio.sunny_day(scene, sun_strength=3.2, sky_strength=1.0, sun_dir=(-0.5, -0.72, 0.7))
    # same framing for everyone so big kids look big and small kids look small
    studio.add_camera(scene, (0.0, -5.5, 0.9), (0.0, 0.0, 1.07), lens=85)
    studio.render(scene, str(out_cards / f"{player['id']}.png"))

    # --- head shot ---
    scene = studio.reset_scene()
    studio.setup_cycles(scene, samples=max(24, samples // 2), width=head_px, height=head_px, transparent=True)
    rig = assemble.spawn_figure("p", look, q)
    rig.anchor.rotation_euler = (0, 0, math.radians(12))
    rig.pose(POSES["ready"])
    bpy.context.view_layer.update()
    head = rig.bones["head"].matrix_world.translation
    build = look.get("build", {})
    centre = Vector((head.x, head.y, head.z + 0.36 * build.get("height", 1.0) ** 0.4))
    studio.sunny_day(scene, sun_strength=3.0, sky_strength=1.05, sun_dir=(-0.45, -0.75, 0.62))
    studio.add_camera(scene, (centre.x + 0.1, -5.2, centre.z + 0.08), tuple(centre), lens=85, ortho_scale=1.24)
    studio.render(scene, str(out_heads / f"{player['id']}.png"))
    return pose


def write_ts(path: Path, players: list, cards_dir: Path, heads_dir: Path):
    def rel(p: Path) -> str:
        r = os.path.relpath(p, path.parent).replace(os.sep, "/")
        return r if r.startswith(".") else "./" + r

    lines = [
        "// Generated by tools/blender/render_cards.py. Do not edit by hand.",
        "",
        "/** Full-figure card pictures, keyed by player id. */",
        "export const CARD_ART: Record<string, number> = {",
    ]
    for p in players:
        lines.append(f"  '{p['id']}': require('{rel(cards_dir / (p['id'] + '.png'))}'),")
    lines += ["};", "", "/** Head shots for small avatars, keyed by player id. */", "export const HEAD_ART: Record<string, number> = {"]
    for p in players:
        lines.append(f"  '{p['id']}': require('{rel(heads_dir / (p['id'] + '.png'))}'),")
    lines += ["};", ""]
    path.write_text("\n".join(lines))


def main():
    argv = sys.argv[1:]
    ap = argparse.ArgumentParser()
    ap.add_argument("--roster", default=str(ROOT / "src" / "data" / "roster.json"))
    ap.add_argument("--out", default=str(ROOT / "assets" / "art"))
    ap.add_argument("--ts", default=str(ROOT / "src" / "data" / "cardArt.ts"))
    ap.add_argument("--only", default="")
    ap.add_argument("--size", default="440x560")
    ap.add_argument("--head", type=int, default=176)
    ap.add_argument("--samples", type=int, default=56)
    ap.add_argument("--skip-existing", action="store_true")
    ap.add_argument("--part", default="", help="i/n: render only every n-th player starting at i (to run several copies at once)")
    args = ap.parse_args(argv)

    roster = json.loads(Path(args.roster).read_text())
    teams = {t["id"]: t for t in roster["teams"]}
    out = Path(args.out)
    cards = out / "cards"
    heads = out / "heads"
    cards.mkdir(parents=True, exist_ok=True)
    heads.mkdir(parents=True, exist_ok=True)
    size = tuple(int(v) for v in args.size.split("x"))
    only = {s for s in args.only.split(",") if s}
    t0 = time.time()
    done = 0
    part = [int(v) for v in args.part.split("/")] if args.part else None
    for index, p in enumerate(roster["players"]):
        if only and p["id"] not in only:
            continue
        if part and index % part[1] != part[0]:
            continue
        if args.skip_existing and (cards / f"{p['id']}.png").exists() and (heads / f"{p['id']}.png").exists():
            continue
        t = time.time()
        pose = render_player(p, teams[p["team"]], cards, heads, size, args.head, args.samples)
        done += 1
        print(f"[cards] {p['id']} ({pose}) {time.time() - t:.1f}s", flush=True)
    write_ts(Path(args.ts), roster["players"], cards, heads)
    print(f"[cards] rendered {done} players in {time.time() - t0:.0f}s, wrote {args.ts}", flush=True)


if __name__ == "__main__":
    main()
